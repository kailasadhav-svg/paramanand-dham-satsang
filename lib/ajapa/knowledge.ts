function normalizeForMatch(text: string): string {
  return text
    .toLowerCase()
    .normalize("NFC")
    .replace(/[\u093c\u0901\u0902]/g, "")
    .replace(/[ऽ']/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function tokensOf(text: string): string[] {
  return normalizeForMatch(text)
    .split(/[\s|,.;:?!«»""''()【】\[\]\/\\-]+/)
    .filter((t) => t.length > 1);
}

